/** Returns the list of prompts for a category id and card type. */
export function getCards(categoryId, type) {
  const category = CATEGORIES.find((c) => c.id === categoryId);
  if (category?.combines) {
    return category.combines.flatMap((id) => CARDS[id]?.[type] ?? []);
  }
  return CARDS[categoryId]?.[type] ?? [];
}
